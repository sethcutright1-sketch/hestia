// Earlier conversation for the "long history" cases of scripts/eval-assistant.ts's deep suite.
//
// server.ts replays at most HISTORY_CHAR_BUDGET (12,000) characters of a stored conversation into every request, counting
// each stored message's text (not its tool results). A real chat that has run for a while sits right at that edge, and
// the risk it creates is specific: the model sees a lot of fluent, confident text about food and shopping, and may answer
// a plain factual question ("what's on the Weekly Groceries list?") from that text instead of calling the tool. These
// exchanges are what such a chat looks like -- a long recipe discussion that never touches a tool -- written out here
// (rather than generated by a model) so every run replays the identical history. The eval script checks the total
// stays within the window.

/** One earlier turn: what the person said, what the assistant answered, and (optionally) the tool calls it made. */
export interface HistoryTurn {
  user: string;
  assistant: string;
  /** Tool calls made during this turn, with the result each returned at the time. */
  steps?: { tool: string; args: Record<string, any>; result: unknown }[];
}

/** Characters server.ts would count for these turns (the person's text plus the assistant's, nothing else). */
export const historyChars = (turns: HistoryTurn[]): number => turns.reduce((n, t) => n + t.user.length + t.assistant.length, 0);

